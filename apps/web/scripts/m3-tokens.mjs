// One-off generator: Material 3 colour tokens from Chyron's seed colour.
// Usage: node scripts/m3-tokens.mjs [#006A6A]  -> prints CSS for src/m3-tokens.css
import {
  argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors, TonalPalette,
} from "@material/material-color-utilities";

const seed = process.argv[2] || "#006A6A";
const roles = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "surface", "onSurface", "surfaceVariant", "onSurfaceVariant",
  "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer",
  "surfaceContainerHigh", "surfaceContainerHighest", "surfaceDim", "surfaceBright",
  "outline", "outlineVariant", "inverseSurface", "inverseOnSurface", "inversePrimary",
  "scrim", "shadow",
];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

// Custom success / warning roles from fixed hues, harmonised in tone with M3 rules
// (light: 40 / on 100 / container 90 / on-container 10; dark: 80 / 20 / 30 / 90).
const custom = { success: "#2E7D32", warning: "#8A5A00" };
function customRoles(hex, dark) {
  const p = TonalPalette.fromHct(Hct.fromInt(argbFromHex(hex)));
  const t = dark ? [80, 20, 30, 90] : [40, 100, 90, 10];
  return [p.tone(t[0]), p.tone(t[1]), p.tone(t[2]), p.tone(t[3])].map(hexFromArgb);
}

function block(dark) {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, 0);
  const lines = roles.map((r) => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(scheme))};`);
  for (const [name, hex] of Object.entries(custom)) {
    const [c, on, cont, onCont] = customRoles(hex, dark);
    lines.push(`  --md-sys-color-${name}: ${c};`, `  --md-sys-color-on-${name}: ${on};`,
      `  --md-sys-color-${name}-container: ${cont};`, `  --md-sys-color-on-${name}-container: ${onCont};`);
  }
  return lines.join("\n");
}

console.log(`/* Generated by scripts/m3-tokens.mjs from seed ${seed}. Do not edit by hand. */`);
console.log(`:root {\n${block(false)}\n}`);
console.log(`:root[data-theme="dark"] {\n${block(true)}\n}`);
