"""Repository interface for Classes & Modules bounded context."""

from typing import Protocol
from uuid import UUID

from app.models.tutor import Tutor


class IClassWorkspaceRepository(Protocol):
    def create_class(self, tutor: Tutor, name: str, description: str | None): ...
    def list_classes(self, tutor: Tutor): ...
    def get_class(self, tutor: Tutor, class_id: UUID): ...
    def update_class(self, classroom, values: dict): ...
    def delete_class(self, classroom): ...
    def list_modules(self, tutor: Tutor, class_id: UUID): ...
    def create_module(self, tutor: Tutor, class_id: UUID, name: str, description: str | None): ...
